def build_model(source: Path) -> tuple[dict, dict, dict[str, bytes]]:
    ssl_doc = load_result(source, "ssl_results.json")
    domain_doc = load_result(source, "domain_results.json")

    certificates = index_rows(ssl_doc["results"], normalise_ssl_row, "ssl_results.json")
    registrations = index_rows(
        domain_doc["results"], normalise_registration_row, "domain_results.json"
    )

    generated_at = max(
        ssl_doc["_parsed_generated_at"], domain_doc["_parsed_generated_at"]
    )
    generated_iso = generated_at.strftime("%Y-%m-%dT%H:%M:%SZ")

    domains = sorted(set(certificates) | set(registrations))
    seen_files: dict[str, str] = {}
    badges: dict[str, bytes] = {}
    entries: list[dict] = []

    for domain in domains:
        certificate = certificates.get(domain)
        registration = registrations.get(domain)
        status = domain_status(certificate, registration)
        filename = badge_filename(domain)
        if filename in seen_files and seen_files[filename] != domain:
            raise BuildError(
                f"badge file name collision: {seen_files[filename]!r} and {domain!r}"
            )
        seen_files[filename] = domain
        path = f"/{BADGES_DIR}/{filename}"
        badges[path.lstrip("/")] = badge_svg(
            domain, status, certificate, registration
        )

        entries.append(
            {
                "domain": domain,
                "status": status,
                "badge": path,
                "certificate": public_certificate(certificate),
                "registration": public_registration(registration),
            }
        )

    domain_counts = Counter(entry["status"] for entry in entries)
    certificate_counts = Counter(
        "error" if row["status"] in SSL_UNREACHABLE else
        row["status"] if row["status"] in SSL_VERDICTS else "unknown"
        for row in certificates.values()
    )
    registration_counts = Counter(
        registration_bucket(row["status"]) for row in registrations.values()
    )

    status_doc = {
        "schema_version": SCHEMA_VERSION,
        "generated_at": generated_iso,
        "overall_status": overall_status([entry["status"] for entry in entries]),
        "checks": {
            "certificates": {
                "generated_at": ssl_doc["_parsed_generated_at"].strftime(
                    "%Y-%m-%dT%H:%M:%SZ"
                ),
                "rows": len(certificates),
            },
            "registrations": {
                "generated_at": domain_doc["_parsed_generated_at"].strftime(
                    "%Y-%m-%dT%H:%M:%SZ"
                ),
                "rows": len(registrations),
            },
        },
        "links": {
            "calendar": f"/{CALENDAR_FILE}",
            "badges": f"/{MANIFEST_FILE}",
        },
        "summary": {
            "domains": {
                "total": len(entries),
                "ok": domain_counts.get("ok", 0),
                "warning": domain_counts.get("warning", 0),
                "critical": domain_counts.get("critical", 0),
                "unknown": domain_counts.get("unknown", 0),
            },
            "certificates": {
                "total": len(certificates),
                "valid": certificate_counts.get("valid", 0),
                "expired": certificate_counts.get("expired", 0),
                "invalid": certificate_counts.get("invalid", 0),
                "error": certificate_counts.get("error", 0),
                "unknown": certificate_counts.get("unknown", 0),
            },
            "registrations": {
                "total": len(registrations),
                "active": registration_counts.get("active", 0),
                "warning": registration_counts.get("warning", 0),
                "urgent": registration_counts.get("urgent", 0),
                "expired": registration_counts.get("expired", 0),
                "unknown": registration_counts.get("unknown", 0),
            },
        },
        "domains": entries,
    }

    manifest_entries: dict[str, dict] = {}
    for entry in entries:
        path = entry["badge"]
        manifest_entries[entry["domain"]] = {
            "path": path,
            "status": entry["status"],
            "color": BADGE_STYLES[entry["status"]][0],
            "sha256": hashlib.sha256(badges[path.lstrip("/")]).hexdigest(),
        }

    manifest = {
        "schema_version": SCHEMA_VERSION,
        "generated_at": generated_iso,
        "badges": manifest_entries,
    }

    files: dict[str, bytes] = {
        STATUS_FILE: (json.dumps(status_doc, indent=2, ensure_ascii=False) + "\n").encode("utf-8"),
        CALENDAR_FILE: build_calendar(certificates, registrations, generated_at),
        MANIFEST_FILE: (json.dumps(manifest, indent=2, ensure_ascii=False) + "\n").encode("utf-8"),
    }
    files.update(badges)
    return status_doc, manifest, files


def public_certificate(row: dict | None) -> dict | None:
    if row is None:
        return None
    return {
        "status": row["status"],
        "category": row["category"],
        "expires_on": row["expires_on"].isoformat() if row["expires_on"] else None,
        "days_left": row["days_left"],
        "provider": row["provider"],
    }


def public_registration(row: dict | None) -> dict | None:
    if row is None:
        return None
    return {
        "status": row["status"],
        "category": row["category"],
        "expires_on": row["expires_on"].isoformat() if row["expires_on"] else None,
        "days_left": row["days_left"],
        "registrar": row["registrar"],
    }


def check_out_path(source: Path, out: Path) -> None:
    source_r = source.resolve()
    out_r = out.resolve()
    if out_r == source_r:
        raise BuildError(f"refusing to use the source tree as output: {out_r}", code=2)
    if out_r in source_r.parents:
        raise BuildError(f"refusing to replace a parent of the source tree: {out_r}", code=2)


def check_existing_bundle(out: Path) -> None:
    if not out.exists():
        return
    if out.is_symlink() or not out.is_dir():
        raise BuildError(f"refusing to replace output path {out}: not a plain directory", code=2)

    names: set[str] = set()
    for entry in out.rglob("*"):
        rel = entry.relative_to(out).as_posix()
        if entry.is_symlink():
            raise BuildError(
                f"refusing to replace {out}: it is not a previous feed bundle "
                f"(found symlink {rel!r})",
                code=2,
            )
        if entry.is_dir():
            if rel != BADGES_DIR:
                raise BuildError(
                    f"refusing to replace {out}: it is not a previous feed bundle "
                    f"(found directory {rel!r})",
                    code=2,
                )
            continue
        if not entry.is_file():
            raise BuildError(
                f"refusing to replace {out}: it is not a previous feed bundle "
                f"(found {rel!r})",
                code=2,
            )
        names.add(rel)
        if rel in {STATUS_FILE, CALENDAR_FILE, MANIFEST_FILE} or BADGE_FILE.match(rel):
            continue
        raise BuildError(
            f"refusing to replace {out}: it is not a previous feed bundle "
            f"(found {rel!r})",
            code=2,
        )

    if names and MANIFEST_FILE not in names:
        raise BuildError(
            f"refusing to replace {out}: it has no {MANIFEST_FILE}, so it is not "
            "a previous CertiWatch feed bundle",
            code=2,
        )


def publish(staging: Path, out: Path) -> None:
    if not out.exists():
        staging.rename(out)
        return

    backup = Path(tempfile.mkdtemp(prefix=f".{out.name}.previous-", dir=out.parent))
    backup.rmdir()
    out.rename(backup)
    try:
        staging.rename(out)
    except OSError:
        backup.rename(out)
        raise
    shutil.rmtree(backup, ignore_errors=True)


def build(source: Path, out: Path) -> tuple[dict, dict, list[str]]:
    source = source.resolve()
    status_doc, manifest, files = build_model(source)
    check_out_path(source, out)
    check_existing_bundle(out)

    out.parent.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix=f".{out.name}.staging-", dir=out.parent))
    try:
        for rel, content in files.items():
            target = staging / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content)

        produced = sorted(
            path.relative_to(staging).as_posix()
            for path in staging.rglob("*")
            if path.is_file()
        )
        expected = sorted(files)
        if produced != expected:
            raise BuildError(
                "feed contents differ from the contract: "
                f"unexpected={sorted(set(produced) - set(expected))} "
                f"missing={sorted(set(expected) - set(produced))}",
                code=2,
            )
        publish(staging, out)
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    return status_doc, manifest, produced


def describe(out: Path, files: list[str]) -> str:
    lines = [f"Feeds: {out}", f"Files: {len(files)}"]
    for rel in files:
        content = (out / rel).read_bytes()
        digest = hashlib.sha256(content).hexdigest()[:16]
        lines.append(f"  {rel:<52} {len(content):>8} bytes  sha256:{digest}")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Build CertiWatch status, badge and calendar feeds."
    )
    parser.add_argument(
        "--source",
        type=Path,
        default=REPO_ROOT,
        help="repository root holding the result JSON files (default: parent of scripts/)",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=REPO_ROOT / "feeds",
        help="feed directory to create (default: ./feeds)",
    )
    args = parser.parse_args()

    try:
        status_doc, _, files = build(args.source, args.out)
    except BuildError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return exc.code
    except OSError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    print(describe(args.out, files))
    print(
        f"Overall: {status_doc['overall_status']}  "
        f"domains={status_doc['summary']['domains']['total']}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
