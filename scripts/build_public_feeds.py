# Statuses that prove a certificate was read; everything else is a failed
# lookup. Unknown future statuses stay "unknown" rather than becoming "ok".
SSL_VERDICTS = frozenset({"valid", "expired", "invalid"})
SSL_UNREACHABLE = frozenset({"dns_error", "timeout", "no_https", "ssl_error", "error"})
REGISTRATION_STATUSES = frozenset(
    {"active", "valid", "warning", "warn", "urgent", "expired"}
)

STATUS_TOKEN = re.compile(r"^[a-z][a-z0-9_]{0,31}$")
DNS_LABEL = re.compile(r"^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$")
DATE_ONLY = re.compile(r"^\d{4}-\d{2}-\d{2}$")
BADGE_FILE = re.compile(r"^badges/[a-z0-9-]{1,40}-[0-9a-f]{32}\.svg$")

MAX_TEXT = 200
MAX_LABEL = 30

BADGE_STYLES = {
    "ok": ("#2f855a", "ok"),
    "warning": ("#b7791f", "warning"),
    "critical": ("#c53030", "critical"),
    "unknown": ("#718096", "unknown"),
}

CSS_GOOD = frozenset({"valid", "active"})
CSS_CRITICAL = frozenset({"expired", "today", "invalid"})


class BuildError(Exception):
    def __init__(self, message: str, code: int = 1) -> None:
        super().__init__(message)
        self.code = code


# ── Input validation ─────────────────────────────────────────────────────────


def reject_symlinked_path(source: Path, rel: str) -> None:
    """Reject a symlink at the result file itself or at a parent component."""
    current = source
    for index, part in enumerate(PurePosixPath(rel).parts):
        current = current / part
        if current.is_symlink():
            where = PurePosixPath(rel).parts[: index + 1]
            raise BuildError(
                f"input {rel!r} is a symlink (at {'/'.join(where)!r}); refusing to read it",
                code=2,
            )


def load_result(source: Path, name: str) -> dict:
    """Read and validate one checker result document."""
    reject_symlinked_path(source, name)
    path = source / name
    if not path.is_file() or path.stat().st_size == 0:
        raise BuildError(f"required input missing or empty: {name}")

    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise BuildError(f"{name}: not valid JSON ({exc})") from exc

    if not isinstance(data, dict):
        raise BuildError(f"{name}: expected a JSON object at the top level")

    generated_at = data.get("generated_at")
    if not isinstance(generated_at, str) or not generated_at.strip():
        raise BuildError(f"{name}: missing or empty 'generated_at'")
    data["_parsed_generated_at"] = parse_timestamp(generated_at, f"{name}: generated_at")

    results = data.get("results")
    if not isinstance(results, list):
        raise BuildError(f"{name}: missing 'results' list")
    if not results:
        raise BuildError(f"{name}: 'results' is empty, refusing to publish empty feeds")
    return data


def parse_timestamp(value: str, where: str) -> datetime_module.datetime:
    """Parse the checkers' ``YYYY-MM-DD HH:MM UTC`` or an ISO-8601 timestamp."""
    text = value.strip()
    if text.endswith(" UTC"):
        text = f"{text[:-4]}+00:00"
    elif text.endswith("Z"):
        text = f"{text[:-1]}+00:00"
    try:
        parsed = datetime_module.datetime.fromisoformat(text)
    except ValueError as exc:
        raise BuildError(f"{where}: unsupported timestamp {value!r}") from exc
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=datetime_module.timezone.utc)
    return parsed.astimezone(datetime_module.timezone.utc)


def parse_port(value: str, where: str) -> int:
    if not value or not value.isdigit():
        raise BuildError(f"{where}: port must be a number")
    port = int(value)
    if not 1 <= port <= 65535:
        raise BuildError(f"{where}: port {port} is outside 1-65535")
    return port


def split_host_port(text: str, where: str) -> tuple[str, int, bool]:
    """Return ``(host, port, is_ipv6)`` for a bare host key."""
    if text.startswith("["):
        end = text.find("]")
        if end < 0:
            raise BuildError(f"{where}: unterminated IPv6 literal")
        host = text[1:end]
        rest = text[end + 1 :]
        try:
            address = ipaddress.ip_address(host)
        except ValueError as exc:
            raise BuildError(f"{where}: invalid IPv6 literal") from exc
        if address.version != 6:
            raise BuildError(f"{where}: brackets are only valid around IPv6")
        if not rest:
            port = 443
        elif rest.startswith(":"):
            port = parse_port(rest[1:], where)
        else:
            raise BuildError(f"{where}: unexpected text after IPv6 literal")
        return address.compressed, port, True

    if text.count(":") > 1:
        raise BuildError(f"{where}: IPv6 literals must be bracketed")
    if text.count(":") == 1:
        host, port_text = text.rsplit(":", 1)
        port = parse_port(port_text, where)
    else:
        host, port = text, 443
    return host, port, False


def canonical_domain(raw: object, where: str) -> str:
    """Validate and canonicalise a host key used in output paths and keys."""
    if not isinstance(raw, str):
        raise BuildError(f"{where}: domain must be a string")
    text = raw.strip()
    if not text:
        raise BuildError(f"{where}: empty domain")
    if any(ord(ch) < 0x20 or ord(ch) == 0x7F for ch in text):
        raise BuildError(f"{where}: domain contains a control character")
    if any(ch.isspace() for ch in text):
        raise BuildError(f"{where}: domain contains whitespace")
    if "://" in text or any(ch in text for ch in "/\\@#?"):
        raise BuildError(f"{where}: {raw!r} is not a host key")

    host, port, is_ipv6 = split_host_port(text, where)
    if is_ipv6:
        host_part = f"[{host}]"
    else:
        try:
            address = ipaddress.ip_address(host)
        except ValueError:
            address = None
        if address is not None:
            if address.version != 4:
                raise BuildError(f"{where}: IPv6 literals must be bracketed")
            host_part = str(address)
        else:
            host = host.lower().rstrip(".")
            if not host or len(host) > 253:
                raise BuildError(f"{where}: invalid host length")
            labels = host.split(".")
            if any(not DNS_LABEL.match(label) for label in labels):
                raise BuildError(f"{where}: {raw!r} is not a valid host name")
            host_part = host

    return host_part if port == 443 else f"{host_part}:{port}"


def clean_text(value: object, where: str) -> str | None:
    """Keep a short public label, never control characters or line breaks."""
    if value is None:
        return None
    if not isinstance(value, str):
        raise BuildError(f"{where}: expected text")
    cleaned = "".join(
        " " if (ord(ch) < 0x20 or 0x7F <= ord(ch) <= 0x9F) else ch for ch in value
    )
    cleaned = re.sub(r"\s+", " ", cleaned).strip()
    return cleaned[:MAX_TEXT] if cleaned else None


def parse_status(value: object, where: str) -> str:
    if not isinstance(value, str):
        raise BuildError(f"{where}: status must be a string")
    status = value.strip().lower()
    if not STATUS_TOKEN.match(status):
        raise BuildError(f"{where}: invalid status {value!r}")
    return status


def parse_days(value: object, where: str) -> int | None:
    if value is None:
        return None
    if isinstance(value, bool) or not isinstance(value, int):
        raise BuildError(f"{where}: days_left must be an integer or null")
    return value


def parse_expiry(value: object, where: str) -> datetime_module.date | None:
    """Return a date, or None for the checkers' explicit "no date" markers."""
    if value is None:
        return None
    if not isinstance(value, str):
        raise BuildError(f"{where}: expiry must be a date string or null")
    text = value.strip()
    if not text or text.upper() in {"N/A", "NA", "UNKNOWN", "NONE"}:
        return None
    if DATE_ONLY.match(text):
        try:
            return datetime_module.date.fromisoformat(text)
        except ValueError as exc:
            raise BuildError(f"{where}: invalid date {value!r}") from exc
    try:
        parsed = datetime_module.datetime.fromisoformat(text.replace("Z", "+00:00"))
    except ValueError as exc:
        raise BuildError(f"{where}: invalid date {value!r}") from exc
    return parsed.date()


# ── Classification (mirrors app.js) ──────────────────────────────────────────


def ssl_category(status: str, days: int | None, is_expired: bool | None) -> str:
    if is_expired is True or status == "expired":
        return "expired"
    if status == "valid":
        if days is None:
            return "valid"
        if days <= 0:
            return "today"
        if days <= 7:
            return "urgent"
        if days <= 30:
            return "warning"
        return "valid"
    if status == "invalid":
        return "invalid"
    if status in SSL_UNREACHABLE:
        return "error"
    return "unknown"


def registration_category(status: str, days: int | None) -> str:
    if status == "expired":
        return "expired"
    if status in {"active", "valid"}:
        if days is None:
            return "active"
        if days <= 0:
            return "expired"
        if days <= 7:
            return "urgent"
        if days <= 30:
            return "warning"
        return "active"
    if status == "urgent":
        return "urgent"
    if status in {"warning", "warn"}:
        return "warning"
    return "unknown"


def registration_bucket(status: str) -> str:
    """Collapse registration statuses onto the summary's five buckets."""
    if status not in REGISTRATION_STATUSES:
        return "unknown"
    if status in {"active", "valid"}:
        return "active"
    if status in {"warning", "warn"}:
        return "warning"
    return status


def domain_status(certificate: dict | None, registration: dict | None) -> str:
    categories = [
        item["category"]
        for item in (certificate, registration)
        if item is not None
    ]
    if any(category in CSS_CRITICAL for category in categories):
        return "critical"
    if certificate is None or registration is None:
        return "warning"
    if all(category == "unknown" for category in categories):
        return "unknown"
    if any(category not in CSS_GOOD for category in categories):
        return "warning"
    return "ok"


def overall_status(domain_statuses: list[str]) -> str:
    if any(status == "critical" for status in domain_statuses):
        return "critical"
    if domain_statuses and all(status == "unknown" for status in domain_statuses):
        return "unknown"
    if any(status in {"warning", "unknown"} for status in domain_statuses):
        return "warning"
    return "ok"


# ── Input normalisation ──────────────────────────────────────────────────────


def normalise_ssl_row(row: object, where: str) -> dict:
    if not isinstance(row, dict):
        raise BuildError(f"{where}: expected an object")
    domain = canonical_domain(row.get("domain"), f"{where}: domain")
    status = parse_status(row.get("status"), f"{where}: status")
    days = parse_days(row.get("days_left"), f"{where}: days_left")
    is_expired = row.get("is_expired")
    if is_expired is not None and not isinstance(is_expired, bool):
        raise BuildError(f"{where}: is_expired must be a boolean or null")
    return {
        "domain": domain,
        "status": status,
        "category": ssl_category(status, days, is_expired),
        "expires_on": parse_expiry(row.get("expires_on"), f"{where}: expires_on"),
        "days_left": days,
        "provider": clean_text(row.get("provider"), f"{where}: provider"),
    }


def normalise_registration_row(row: object, where: str) -> dict:
    if not isinstance(row, dict):
        raise BuildError(f"{where}: expected an object")
    domain = canonical_domain(row.get("domain"), f"{where}: domain")
    status = parse_status(row.get("status"), f"{where}: status")
    days = parse_days(row.get("days_left"), f"{where}: days_left")
    return {
        "domain": domain,
        "status": status,
        "category": registration_category(status, days),
        "expires_on": parse_expiry(row.get("expiry_date"), f"{where}: expiry_date"),
        "days_left": days,
        "registrar": clean_text(row.get("registrar"), f"{where}: registrar"),
    }


def index_rows(rows: list, normaliser, label: str) -> dict[str, dict]:
    indexed: dict[str, dict] = {}
    for index, row in enumerate(rows, start=1):
        item = normaliser(row, f"{label} row {index}")
        domain = item["domain"]
        if domain in indexed:
            raise BuildError(f"{label}: duplicate domain {domain!r}; refusing to guess")
        indexed[domain] = item
    return indexed


# ── Output helpers ───────────────────────────────────────────────────────────


def xml_escape(value: str) -> str:
    """Escape for XML text/attributes and drop characters XML 1.0 forbids."""
    cleaned = "".join(
        " "
        if (
            ord(ch) < 0x20 and ch not in "\t\n\r"
            or 0x7F <= ord(ch) <= 0x9F
        )
        else ch
        for ch in value
    )
    return html.escape(cleaned, quote=True)


def ics_escape(value: str) -> str:
    """Escape an RFC 5545 TEXT value (backslash, semicolon, comma, newline)."""
    cleaned = "".join(
        " " if (ord(ch) < 0x20 and ch not in "\t\n\r") or 0x7F <= ord(ch) <= 0x9F else ch
        for ch in value
    )
    return (
        cleaned.replace("\\", "\\\\")
        .replace(";", "\\;")
        .replace(",", "\\,")
        .replace("\r\n", "\\n")
        .replace("\n", "\\n")
        .replace("\r", "\\n")
    )


def fold_ics_line(line: str) -> str:
    """Fold one content line at 75 octets without splitting a UTF-8 codepoint."""
    folded: list[str] = []
    current = ""
    current_bytes = 0
    for character in line:
        width = len(character.encode("utf-8"))
        if current_bytes + width > 75:
            folded.append(current)
            current = " " + character
            current_bytes = 1 + width
        else:
            current += character
            current_bytes += width
    folded.append(current)
    return "\r\n".join(folded)


def badge_filename(domain: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", domain.lower()).strip("-")[:40].strip("-")
    slug = slug or "host"
    digest = hashlib.sha256(domain.encode("utf-8")).hexdigest()[:32]
    return f"{slug}-{digest}.svg"


def truncate(value: str, limit: int = MAX_LABEL) -> str:
    return value if len(value) <= limit else f"{value[: limit - 3]}..."


def badge_svg(
    domain: str,
    status: str,
    certificate: dict | None,
    registration: dict | None,
) -> bytes:
    color, label = BADGE_STYLES.get(status, BADGE_STYLES["unknown"])
    visible = truncate(domain)
    left_width = int(round(len(visible) * 6.2)) + 12
    right_width = int(round(len(label) * 6.2)) + 12
    width = left_width + right_width

    details: list[str] = []
    if certificate is None:
        details.append("certificate not checked")
    else:
        expiry = certificate["expires_on"].isoformat() if certificate["expires_on"] else "no date"
        details.append(f"certificate {certificate['status']}, expires {expiry}")
    if registration is None:
        details.append("registration not checked")
    else:
        expiry = registration["expires_on"].isoformat() if registration["expires_on"] else "no date"
        details.append(f"registration {registration['status']}, expires {expiry}")
    title = f"{domain}: {'; '.join(details)}"
    aria = f"{domain} status {status}"

    svg = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="20" '
        f'role="img" aria-label="{xml_escape(aria)}">\n'
        f"  <title>{xml_escape(title)}</title>\n"
        f'  <rect width="{width}" height="20" rx="3" fill="#4a5568"/>\n'
        f'  <rect x="{left_width}" width="{right_width}" height="20" rx="3" fill="{color}"/>\n'
        '  <g fill="#ffffff" font-family="Verdana,DejaVu Sans,sans-serif" '
        'font-size="11" text-anchor="middle">\n'
        f'    <text x="{left_width // 2}" y="14">{xml_escape(visible)}</text>\n'
        f'    <text x="{left_width + right_width // 2}" y="14">{xml_escape(label)}</text>\n'
        "  </g>\n"
        "</svg>\n"
    )
    return svg.encode("utf-8")


def days_phrase(days: int | None) -> str:
    if days is None:
        return "no day count"
    if days < 0:
        unit = "day" if days == -1 else "days"
        return f"expired {-days} {unit} ago"
    if days == 0:
        return "expires today"
    unit = "day" if days == 1 else "days"
    return f"{days} {unit} left"


def calendar_event(
    kind: str,
    domain: str,
    expiry: datetime_module.date,
    description: str,
    dtstamp: datetime_module.datetime,
) -> list[str]:
    uid_source = f"{kind}|{domain}|{expiry.isoformat()}"
    uid = f"{hashlib.sha256(uid_source.encode('utf-8')).hexdigest()[:32]}@certiwatch.pages.dev"
    next_day = expiry + datetime_module.timedelta(days=1)
    summary = (
        f"SSL certificate expires: {domain}"
        if kind == "certificate"
        else f"Domain registration expires: {domain}"
    )
    category = "SSL certificate" if kind == "certificate" else "Domain registration"
    return [
        "BEGIN:VEVENT",
        f"UID:{uid}",
        f"DTSTAMP:{dtstamp.strftime('%Y%m%dT%H%M%SZ')}",
        f"DTSTART;VALUE=DATE:{expiry.strftime('%Y%m%d')}",
        f"DTEND;VALUE=DATE:{next_day.strftime('%Y%m%d')}",
        f"SUMMARY:{ics_escape(summary)}",
        f"DESCRIPTION:{ics_escape(description)}",
        f"CATEGORIES:{ics_escape(category)}",
        "TRANSP:TRANSPARENT",
        "END:VEVENT",
    ]


def build_calendar(
    certificates: dict[str, dict],
    registrations: dict[str, dict],
    dtstamp: datetime_module.datetime,
) -> bytes:
    events: list[tuple[datetime_module.date, str, int, list[str]]] = []
    for domain, row in certificates.items():
        if row["expires_on"] is None:
            continue
        description = (
            f"SSL certificate for {domain} expires {row['expires_on'].isoformat()} "
            f"({days_phrase(row['days_left'])}). Status: {row['status']}."
        )
        if row["provider"]:
            description += f" Issuer: {row['provider']}."
        events.append(
            (
                row["expires_on"],
                domain,
                0,
                calendar_event(
                    "certificate", domain, row["expires_on"], description, dtstamp
                ),
            )
        )
    for domain, row in registrations.items():
        if row["expires_on"] is None:
            continue
        description = (
            f"Domain registration for {domain} expires {row['expires_on'].isoformat()} "
            f"({days_phrase(row['days_left'])}). Status: {row['status']}."
        )
        if row["registrar"]:
            description += f" Registrar: {row['registrar']}."
        events.append(
            (
                row["expires_on"],
                domain,
                1,
                calendar_event(
                    "registration", domain, row["expires_on"], description, dtstamp
                ),
            )
        )

    events.sort(key=lambda event: (event[0], event[1], event[2]))

    lines = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        "PRODID:-//CertiWatch//Public Expiry Feed//EN",
        "CALSCALE:GREGORIAN",
        "METHOD:PUBLISH",
        "X-WR-CALNAME:CertiWatch certificate and domain expiries",
        "X-WR-CALDESC:Certificate and registration expiry dates published by CertiWatch.",
        "REFRESH-INTERVAL;VALUE=DURATION:PT1H",
        "X-PUBLISHED-TTL:PT1H",
    ]
    for _, _, _, event_lines in events:
        lines.extend(event_lines)
    lines.append("END:VCALENDAR")

    text = "\r\n".join(fold_ics_line(line) for line in lines) + "\r\n"
    return text.encode("utf-8")


