#!/usr/bin/env python3
"""Build CertiWatch's public status, badge and calendar feeds.

The feeds are a machine-readable view of the same two result files the
dashboard already publishes:

    ssl_results.json      generated by src/ssl/scripts/check_ssl.py
    domain_results.json   generated by src/domain/scripts/check_domains.py

Output contract (all paths relative to ``--out``, UTF-8, deterministic):

    status.json                     summary endpoint (application/json)
    expiries.ics                    RFC 5545 calendar (text/calendar)
    badges/manifest.json            domain -> badge mapping (application/json)
    badges/<slug>-<sha256:32>.svg   one badge per domain (image/svg+xml)

``links`` and ``badge`` values are root-relative URL paths (``/expiries.ics``,
``/badges/<file>.svg``). The file layout above is the same path with the
leading slash removed, so ``https://<site>/status.json`` can be fetched and its
``badge`` value used as ``https://<site>`` + ``badge``.

``status.json`` is a summary, not a copy of the checker output:

    {
      "schema_version": 1,
      "generated_at": "2026-04-26T01:11:00Z",   # latest input timestamp
      "overall_status": "ok",                    # ok|warning|critical|unknown
      "checks": {
        "certificates":  {"generated_at": "...", "rows": 10},
        "registrations": {"generated_at": "...", "rows": 10}
      },
      "links": {"calendar": "/expiries.ics", "badges": "/badges/manifest.json"},
      "summary": {
        "domains":        {"total": 10, "ok": 10, "warning": 0,
                           "critical": 0, "unknown": 0},
        "certificates":   {"total": 10, "valid": 10, "expired": 0,
                           "invalid": 0, "error": 0, "unknown": 0},
        "registrations":  {"total": 10, "active": 10, "warning": 0,
                           "urgent": 0, "expired": 0, "unknown": 0}
      },
      "domains": [
        {
          "domain": "example.com",
          "status": "ok",                        # badge severity
          "badge": "/badges/example-com-<sha256:32>.svg",
          "certificate": {
            "status": "valid",                   # raw checker status
            "category": "valid",                 # dashboard category
            "expires_on": "2026-06-25",
            "days_left": 60,
            "provider": "Let's Encrypt"
          },
          "registration": {                      # null when not checked
            "status": "active",
            "category": "active",
            "expires_on": "2027-06-25",
            "days_left": 425,
            "registrar": "Example Registrar"
          }
        }
      ]
    }

Categories mirror the dashboard (``app.js``): certificate ``expired|today|
urgent|warning|valid|invalid|error|unknown`` (today <= 0 days, urgent <= 7,
warning <= 30); registration ``expired|urgent|warning|active|unknown``.
A domain is ``critical`` when a certificate is expired/today/invalid or a
registration is expired; ``warning`` when a check is missing, unreachable,
unknown, or inside a 30-day window; ``unknown`` when both checks are unknown.

``expiries.ics`` contains one all-day VEVENT per certificate expiry and per
registration expiry that has a real date. Events are sorted by start date,
domain and kind. ``UID`` is the first 32 hex characters of
``sha256(kind|domain|YYYY-MM-DD)`` plus ``@certiwatch.pages.dev``, so a rebuild
updates the same event instead of duplicating it.

Safety rules:

* Only a fixed schema is emitted. Raw checker ``error`` text, configuration,
  environment variables, file paths and credentials never reach an output.
* Domain keys must be real host keys (``host``, ``host:port`` or a bracketed
  IPv6 literal) and are canonicalised; a URL, path, userinfo, control
  character, bad label or out-of-range port fails the build. A duplicate
  domain in one result file fails too: the feed never guesses which row wins.
* Badge file names are ``<readable slug>-<sha256(domain)[:32]>.svg``. The slug
  is cosmetic; the hash is what keeps two domains such as ``exa-mple.com`` and
  ``exa.mple.com`` apart.
* SVG and ICS text is XML/ICS escaped, and every dropped/normalised value is
  deterministic.
* Output is written to a hidden sibling and swapped in at the end. A
  non-empty destination is replaced only when every entry is a feed this
  builder produces and ``badges/manifest.json`` is present; otherwise it is
  refused and left untouched.

Usage:
    python3 scripts/build_public_feeds.py --out feeds
    python3 scripts/build_public_feeds.py --source . --out /tmp/feeds

Exit codes:
    0  feeds built and verified
    1  required input missing, empty, malformed or inconsistent
    2  unsafe output path or unmanaged destination
"""

