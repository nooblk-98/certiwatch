#!/usr/bin/env python3
"""Assemble the Cloudflare Pages publish directory for CertiWatch.

The published bundle is an explicit allowlist. Nothing else in the repository
is copied, so the repository layout (sources, images, workflows) never reaches
the public site.

Required inputs (build fails without them):
    index.html           dashboard shell
    ssl_results.json     generated by src/ssl/scripts/check_ssl.py
    domain_results.json  generated by src/domain/scripts/check_domains.py
    pages/_headers       cache policy, published as _headers

Optional inputs, copied only when present:
    app.js               dashboard script, split out of index.html
    style.css            dashboard stylesheet, split out of index.html
    history.json         public history, generated by src/monitor_state.py

Generated by this build (never read from the repository):
    status.json          summary endpoint
    expiries.ics         RFC 5545 expiry calendar
    badges/manifest.json domain -> badge mapping
    badges/*.svg         one deterministic badge per domain

The feed files are built by scripts/build_public_feeds.py into the same hidden
staging directory. Badge names are dynamic, so the allowlist accepts only the
manifest plus names matching the exact ``<slug>-<sha256>.svg`` pattern; nothing
else may appear under badges/.

Adding a file to the published site is therefore a reviewed change to this
list, not a side effect of the repository growing.

Safety rules enforced here:

* Inputs must be regular files. A symlink is rejected, including one used as a
  parent directory (``pages`` pointing elsewhere), so the bundle can never pick
  up a file from outside the checkout.
* The output directory may live outside the source tree. Inside the source tree
  only the designated ``dist`` directory is allowed, and a non-empty
  destination is only replaced when every entry in it is a file this builder
  itself can produce. Anything else is refused instead of deleted.
* A run whose SSL rows *all* failed before a certificate was read (DNS, connect,
  TLS handshake or entry errors) is not a monitoring result: it is a runner
  without egress or a network outage. Publishing it would replace real data
  with "everything is broken", so the build fails and leaves production alone.
  Genuine certificate verdicts - ``valid``, ``expired``, ``invalid`` - always
  publish, even when most rows are failures.

Usage:
    python3 scripts/build_dist.py                # build ./dist
    python3 scripts/build_dist.py --out dist --source .

Exit codes:
    0  bundle built and verified
    1  required input missing, empty or malformed
    2  unsafe input or output path, or unexpected bundle contents
"""

from __future__ import annotations

import argparse
import datetime
import hashlib
import json
import re
import shutil
import sys
import tempfile
from collections import Counter
from pathlib import Path, PurePosixPath

SCRIPT_DIR = Path(__file__).resolve().parent
if str(SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPT_DIR))

import build_public_feeds  # noqa: E402  (lives beside this script)

REPO_ROOT = SCRIPT_DIR.parent

# source path (relative to --source) -> path inside the published bundle
REQUIRED_FILES = {
    "index.html": "index.html",
    "ssl_results.json": "ssl_results.json",
    "domain_results.json": "domain_results.json",
    "pages/_headers": "_headers",
}

OPTIONAL_FILES = {
    "app.js": "app.js",
    "style.css": "style.css",
    "history.json": "history.json",
}

# Flat allowlist entries. The badge directory is handled separately because its
# names are derived from the monitored domains on every run.
FLAT_BUNDLE_NAMES = (
    frozenset(REQUIRED_FILES.values())
    | frozenset(OPTIONAL_FILES.values())
    | frozenset({build_public_feeds.STATUS_FILE, build_public_feeds.CALENDAR_FILE})
)
BADGES_DIR = build_public_feeds.BADGES_DIR
BADGE_MANIFEST = build_public_feeds.MANIFEST_FILE
BADGE_FILE = re.compile(build_public_feeds.BADGE_FILE.pattern)

# The only directory the builder may write inside the source tree.
DESIGNATED_OUTPUT = "dist"

# Result files must be real check output, not an empty placeholder.
JSON_FILES = ("ssl_results.json", "domain_results.json")
HISTORY_FILE = "history.json"

# Only these statuses prove a certificate was actually read and judged. Anything
# else - DNS/connect/handshake failures, input errors, a missing or unknown
# status - is treated as "not observed", so a future checker status can never
# silently weaken the gate. See the module docstring.
OBSERVED_SSL_STATUSES = frozenset({"valid", "expired", "invalid"})


class BuildError(Exception):
    def __init__(self, message: str, code: int = 1) -> None:
        super().__init__(message)
        self.code = code


def reject_symlinked_path(source: Path, rel: str) -> None:
    """Reject a symlink at the file itself or at any parent component."""
    current = source
    for index, part in enumerate(PurePosixPath(rel).parts):
        current = current / part
        if current.is_symlink():
            where = PurePosixPath(rel).parts[: index + 1]
            raise BuildError(
                f"input {rel!r} is a symlink (at {'/'.join(where)!r}); refusing to publish it",
                code=2,
            )


def validate_ssl_coverage(results: list) -> None:
    """Refuse a run where no certificate was read at all."""
    observed = sum(
        1 for row in results if isinstance(row, dict) and row.get("status") in OBSERVED_SSL_STATUSES
    )
    if observed:
        return

    counts = Counter(
        row.get("status", "<missing>") if isinstance(row, dict) else "<not-an-object>"
        for row in results
    )
    summary = ", ".join(f"{status}={count}" for status, count in sorted(counts.items()))
    raise BuildError(
        f"ssl_results.json: all {len(results)} rows are connection/DNS failures "
        f"({summary}); no certificate was read, so this run must not replace the "
        "published results"
    )


def validate_result_json(path: Path) -> None:
    """Fail on unreadable JSON or a result file with no rows."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise BuildError(f"{path.name}: not valid JSON ({exc})") from exc

    if not isinstance(data, dict):
        raise BuildError(f"{path.name}: expected a JSON object at the top level")

    generated_at = data.get("generated_at")
    if not isinstance(generated_at, str) or not generated_at.strip():
        raise BuildError(f"{path.name}: missing or empty 'generated_at'")

    results = data.get("results")
    if not isinstance(results, list):
        raise BuildError(f"{path.name}: missing 'results' list")
    if not results:
        raise BuildError(
            f"{path.name}: 'results' is empty, refusing to publish an empty dashboard"
        )

    if path.name == "ssl_results.json":
        validate_ssl_coverage(results)


def validate_history_json(path: Path) -> None:
    """Fail on unreadable or structurally wrong public history.

    History is optional on a first run, but a present file must be publishable
    as-is: one snapshot per date with the two public row lists.
    """
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise BuildError(f"{path.name}: not valid JSON ({exc})") from exc

    if not isinstance(data, dict):
        raise BuildError(f"{path.name}: expected a JSON object at the top level")
    extra = set(data) - {"snapshots"}
    if extra:
        raise BuildError(
            f"{path.name}: unexpected top-level keys {sorted(extra)!r}; "
            "only public snapshots may be published"
        )
    snapshots = data.get("snapshots")
    if not isinstance(snapshots, list):
        raise BuildError(f"{path.name}: missing 'snapshots' list")
    if not snapshots:
        raise BuildError(f"{path.name}: 'snapshots' is empty, refusing to publish it")

    row_keys = {
        "ssl": {"domain", "days_left", "status", "fingerprint_sha256"},
        "domains": {"domain", "days_left", "status"},
    }
    dates: set[str] = set()
    for index, snapshot in enumerate(snapshots):
        where = f"{path.name}: snapshots[{index}]"
        if not isinstance(snapshot, dict):
            raise BuildError(f"{where}: expected an object")
        extra = set(snapshot) - {"date", "ssl", "domains"}
        if extra:
            raise BuildError(
                f"{where}: unexpected keys {sorted(extra)!r}; private metadata "
                "must not enter the public history"
            )
        date = snapshot.get("date")
        if not isinstance(date, str):
            raise BuildError(f"{where}: missing 'date'")
        try:
            canonical = datetime.date.fromisoformat(date).isoformat()
        except ValueError as exc:
            raise BuildError(f"{where}: 'date' must be YYYY-MM-DD") from exc
        if canonical in dates:
            raise BuildError(f"{path.name}: duplicate snapshot date {canonical!r}")
        dates.add(canonical)
        for key, allowed in row_keys.items():
            rows = snapshot.get(key)
            if not isinstance(rows, list):
                raise BuildError(f"{where}: missing {key!r} list")
            for row_index, row in enumerate(rows):
                if not isinstance(row, dict):
                    raise BuildError(f"{where}.{key}[{row_index}]: expected an object")
                row_extra = set(row) - allowed
                if row_extra:
                    raise BuildError(
                        f"{where}.{key}[{row_index}]: unexpected keys "
                        f"{sorted(row_extra)!r}"
                    )
                if not isinstance(row.get("domain"), str) or not row["domain"]:
                    raise BuildError(f"{where}.{key}[{row_index}]: missing 'domain'")


def plan_bundle(source: Path) -> dict[str, str]:
    """Return source-relative path -> bundle path for this build."""
    missing: list[str] = []
    for rel in REQUIRED_FILES:
        reject_symlinked_path(source, rel)
        path = source / rel
        if not path.is_file() or path.stat().st_size == 0:
            missing.append(rel)
    if missing:
        raise BuildError(f"required input missing or empty: {', '.join(missing)}")

    for rel in OPTIONAL_FILES:
        reject_symlinked_path(source, rel)

    for name in JSON_FILES:
        validate_result_json(source / name)

    history = source / HISTORY_FILE
    if history.exists():
        if not history.is_file() or history.stat().st_size == 0:
            raise BuildError(f"{HISTORY_FILE}: present but empty or not a regular file")
        validate_history_json(history)

    plan = dict(REQUIRED_FILES)
    for rel, dest in OPTIONAL_FILES.items():
        if (source / rel).is_file():
            plan[rel] = dest
    return plan


def check_out_path(source: Path, out: Path) -> None:
    """Refuse destructive output locations."""
    source_r = source.resolve()
    out_r = out.resolve()
    if out_r == source_r:
        raise BuildError(f"refusing to use the source tree as output: {out_r}", code=2)
    if out_r in source_r.parents:
        raise BuildError(f"refusing to replace a parent of the source tree: {out_r}", code=2)
    if source_r in out_r.parents:
        rel = out_r.relative_to(source_r)
        if rel.parts != (DESIGNATED_OUTPUT,):
            raise BuildError(
                f"refusing to write inside the source tree at {rel.as_posix()!r}; "
                f"the only allowed in-tree output is {DESIGNATED_OUTPUT!r}",
                code=2,
            )


def check_existing_bundle(out: Path) -> None:
    """Refuse to delete a non-empty directory we did not create."""
    if not out.exists():
        return
    if out.is_symlink() or not out.is_dir():
        raise BuildError(f"refusing to replace output path {out}: not a plain directory", code=2)

    names: set[str] = set()
    for entry in out.rglob("*"):
        rel = entry.relative_to(out).as_posix()
        if entry.is_symlink():
            raise BuildError(
                f"refusing to replace {out}: it is not a previous CertiWatch bundle "
                f"(found symlink {rel!r})",
                code=2,
            )
        if entry.is_dir():
            if rel != BADGES_DIR:
                raise BuildError(
                    f"refusing to replace {out}: it is not a previous CertiWatch "
                    f"bundle (found directory {rel!r})",
                    code=2,
                )
            continue
        if not entry.is_file():
            raise BuildError(
                f"refusing to replace {out}: it is not a previous CertiWatch bundle "
                f"(found {rel!r})",
                code=2,
            )
        if rel not in FLAT_BUNDLE_NAMES and rel != BADGE_MANIFEST and not BADGE_FILE.match(rel):
            raise BuildError(
                f"refusing to replace {out}: it is not a previous CertiWatch bundle "
                f"(found {rel!r})",
                code=2,
            )
        names.add(rel)

    # A bundle we produced always contains _headers, so a directory without it
    # is somebody else's data even if every file name happens to match.
    if names and "_headers" not in names:
        raise BuildError(
            f"refusing to replace {out}: it has no _headers, so it is not a "
            "previous CertiWatch bundle",
            code=2,
        )


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 256), b""):
            digest.update(chunk)
    return digest.hexdigest()


def publish(staging: Path, out: Path) -> None:
    """Swap a finished staging directory into place, keeping the old bundle."""
    if not out.exists():
        staging.rename(out)
        return

    backup = Path(tempfile.mkdtemp(prefix=f".{out.name}.previous-", dir=out.parent))
    backup.rmdir()
    out.rename(backup)
    try:
        staging.rename(out)
    except OSError:
        backup.rename(out)
        raise
    shutil.rmtree(backup, ignore_errors=True)


def build(source: Path, out: Path) -> list[str]:
    source = source.resolve()
    plan = plan_bundle(source)
    check_out_path(source, out)

    # Refuse before creating anything: an unmanaged destination is never deleted.
    check_existing_bundle(out)

    out.parent.mkdir(parents=True, exist_ok=True)
    # Build beside the destination so the final rename stays on one filesystem,
    # and never leave a half-filled bundle where a deploy step could pick it up.
    staging = Path(tempfile.mkdtemp(prefix=f".{out.name}.staging-", dir=out.parent))
    try:
        for rel, dest in plan.items():
            target = staging / dest
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source / rel, target)

        feed_root = staging / ".feeds"
        try:
            _, _, feed_files = build_public_feeds.build(source, feed_root)
        except build_public_feeds.BuildError as exc:
            raise BuildError(f"public feeds: {exc}", code=exc.code) from exc

        for rel in feed_files:
            target = staging / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(feed_root / rel, target)
        shutil.rmtree(feed_root)

        expected = sorted([*plan.values(), *feed_files])
        produced = sorted(
            p.relative_to(staging).as_posix() for p in staging.rglob("*") if p.is_file()
        )
        if produced != expected:
            raise BuildError(
                "bundle contents differ from the allowlist: "
                f"unexpected={sorted(set(produced) - set(expected))} "
                f"missing={sorted(set(expected) - set(produced))}",
                code=2,
            )

        publish(staging, out)
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    return produced


def describe(out: Path, files: list[str]) -> str:
    lines = [f"Bundle: {out}", f"Files: {len(files)}"]
    for rel in files:
        path = out / rel
        lines.append(f"  {rel:<22} {path.stat().st_size:>8} bytes  sha256:{sha256(path)[:16]}")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Build the Cloudflare Pages publish directory.")
    parser.add_argument(
        "--source",
        type=Path,
        default=REPO_ROOT,
        help="repository root to read from (default: parent of scripts/)",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=REPO_ROOT / "dist",
        help="publish directory to create (default: ./dist)",
    )
    args = parser.parse_args()

    try:
        files = build(args.source, args.out)
    except BuildError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return exc.code
    except OSError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    print(describe(args.out, files))
    return 0


if __name__ == "__main__":
    sys.exit(main())
